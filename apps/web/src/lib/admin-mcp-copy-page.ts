function adminMcpToolLines(locale: Locale) {
  return MCP_TOOL_MANIFEST
    .filter((tool) => tool.surfaces.includes("admin"))
    .map((tool) => `- \`${tool.name}\` (${ADMIN_GRANT_LABELS[locale][tool.adminGrant]}): ${tool.description[locale]}`);
}

